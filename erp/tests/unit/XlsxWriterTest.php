<?php

namespace Tests\Unit;

use App\Libraries\SheetIO;
use CodeIgniter\Test\CIUnitTestCase;
use PhpOffice\PhpSpreadsheet\IOFactory;

/** The streamed .xlsx opens as a normal workbook with the same layout and values as before. */
final class XlsxWriterTest extends CIUnitTestCase
{
    private function open(string $bytes): \PhpOffice\PhpSpreadsheet\Spreadsheet
    {
        $f = tempnam(sys_get_temp_dir(), 'xt') . '.xlsx';
        file_put_contents($f, $bytes);
        $book = IOFactory::createReader('Xlsx')->load($f);
        unlink($f);

        return $book;
    }

    public function testWorkbookKeepsLayoutTypesAndFormats(): void
    {
        $rows = [];
        for ($i = 1; $i <= 1500; $i++) {
            $rows[] = ['no' => 'INV-' . $i, 'date' => '2026-10-0' . (1 + $i % 9), 'amount' => (string) ($i * 100 + 0.5), 'qty' => (string) $i, 'note' => $i === 7 ? "=HYPERLINK(\"x\")\x01 & <b>" : 'Line ' . $i];
        }
        $bytes = SheetIO::xlsx([[
            'title' => 'Invoices: Oct/2026', 'rows' => $rows, 'totals' => ['amount'], 'notes' => ['Amounts in ₹'],
            'columns' => [['key' => 'no', 'label' => 'Number'], ['key' => 'date', 'label' => 'Date', 'type' => 'date'], ['key' => 'amount', 'label' => 'Amount', 'type' => 'money'],
                ['key' => 'qty', 'label' => 'Qty', 'type' => 'int'], ['key' => 'note', 'label' => 'Note', 'width' => 40]],
        ], ['title' => 'Invoices', 'rows' => [], 'columns' => [['key' => 'x', 'label' => 'X']]]], ['Report' => 'Test', 'Generated by' => 'Tester']);
        $this->assertStringStartsWith('PK', $bytes);

        $book = $this->open($bytes);
        $this->assertSame(['About', 'Invoices  Oct 2026', 'Invoices'], $book->getSheetNames(), 'About sheet first; invalid characters replaced; names unique');
        $about = $book->getSheet(0);
        $this->assertSame('Generated by', (string) $about->getCell('A2')->getValue());
        $this->assertTrue($about->getStyle('A1')->getFont()->getBold());

        $ws = $book->getSheet(1);
        $this->assertSame('Number', (string) $ws->getCell('A1')->getValue());
        $this->assertTrue($ws->getStyle('A1')->getFont()->getBold());
        $this->assertSame('FF1B1B1B', $ws->getStyle('A1')->getFill()->getStartColor()->getARGB());
        $this->assertSame('A2', $ws->getFreezePane());
        $this->assertSame('A1:E1501', $ws->getAutoFilter()->getRange());
        $this->assertSame('INV-1500', (string) $ws->getCell('A1501')->getValue());
        $this->assertEqualsWithDelta(150000.5, (float) $ws->getCell('C1501')->getValue(), 0.001);
        $this->assertSame('#,##,##0.00;[Red]-#,##,##0.00', $ws->getStyle('C2')->getNumberFormat()->getFormatCode());
        $this->assertSame(1500, (int) (string) $ws->getCell('D1501')->getValue());
        $this->assertSame('dd-mm-yyyy', $ws->getStyle('B2')->getNumberFormat()->getFormatCode());
        $this->assertSame('2026-10-02', \PhpOffice\PhpSpreadsheet\Shared\Date::excelToDateTimeObject((float) (string) $ws->getCell('B2')->getValue())->format('Y-m-d'));
        $this->assertSame('=HYPERLINK("x") & <b>', (string) $ws->getCell('E8')->getValue(), 'text stays text (no formula), control characters removed');
        $this->assertContains($ws->getCell('E8')->getDataType(), ['s', 'inlineStr'], 'stored as text');
        $this->assertSame('TOTAL', (string) $ws->getCell('A1502')->getValue());
        $this->assertSame('=SUBTOTAL(9,C2:C1501)', (string) $ws->getCell('C1502')->getValue());
        $this->assertSame('Amounts in ₹', (string) $ws->getCell('A1504')->getValue());
        $this->assertEqualsWithDelta(40.0, $ws->getColumnDimension('E')->getWidth(), 0.01);
    }

    public function testOwnImportReadsAnExportedTemplate(): void
    {
        $bytes = SheetIO::xlsx([['title' => 'Contacts', 'columns' => [['key' => 'name', 'label' => 'name'], ['key' => 'phone', 'label' => 'phone']],
            'rows' => [['name' => 'Example Clinic', 'phone' => '9800000000']], 'notes' => ['type: customer']]]);
        $f = tempnam(sys_get_temp_dir(), 'xt') . '.xlsx';
        file_put_contents($f, $bytes);
        $read = SheetIO::read($f, 'template.xlsx');
        unlink($f);
        $this->assertSame(['name', 'phone'], $read['headers']);
        $this->assertSame(['name' => 'Example Clinic', 'phone' => '9800000000'], $read['rows'][0]);
    }

    public function testMemoryStaysFlatForLargeExports(): void
    {
        $rows = (static function () {
            for ($i = 0; $i < 60000; $i++) {
                yield ['a' => 'Lead ' . $i, 'b' => (string) $i, 'c' => '2026-01-01 10:00:00', 'd' => str_repeat('x', 40)];
            }
        })();
        $before = memory_get_usage();
        $bytes  = SheetIO::xlsx([['title' => 'Big', 'rows' => $rows, 'columns' => [['key' => 'a', 'label' => 'A'], ['key' => 'b', 'label' => 'B', 'type' => 'int'], ['key' => 'c', 'label' => 'C', 'type' => 'date'], ['key' => 'd', 'label' => 'D']]]]);
        $this->assertLessThan(40 * 1048576, memory_get_usage() - $before - strlen($bytes), '240,000 cells without holding them in memory');
        $this->assertGreaterThan(100000, strlen($bytes));
    }
}
