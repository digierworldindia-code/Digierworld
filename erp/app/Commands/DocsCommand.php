<?php

namespace App\Commands;

use CodeIgniter\CLI\BaseCommand;
use CodeIgniter\CLI\CLI;
use Config\Permissions;

/**
 * php spark dgr:docs — regenerates docs/02-PERMISSIONS.md (from the code
 * registry + DB role grants) and docs/03-SCHEMA.md (from the live,
 * migrated database: tables, columns, keys, FKs, Mermaid ERD).
 */
class DocsCommand extends BaseCommand
{
    protected $group       = 'DGR Office';
    protected $name        = 'dgr:docs';
    protected $description = 'Generate permission matrix and schema/ERD docs from code and the live database.';

    public function run(array $params)
    {
        $dir = ROOTPATH . 'docs' . DIRECTORY_SEPARATOR;
        if (! is_dir($dir)) {
            mkdir($dir, 0755, true);
        }
        file_put_contents($dir . '02-PERMISSIONS.md', $this->permissions());
        CLI::write('Wrote docs/02-PERMISSIONS.md', 'green');
        file_put_contents($dir . '03-SCHEMA.md', $this->schema());
        CLI::write('Wrote docs/03-SCHEMA.md', 'green');

        return EXIT_SUCCESS;
    }

    private function permissions(): string
    {
        $cfg   = config(Permissions::class);
        $roles = [];
        $grant = [];
        foreach ($cfg->starterRoles as $code => $r) {
            $roles[] = ['code' => $code, 'name' => $r['name'], 'description' => $r['description'], 'is_super' => $r['perms'] === ['*'] ? 1 : 0];
            foreach ($r['perms'] as $perm) {
                $grant[$perm][$code] = true;
            }
        }

        $md  = "# Permission registry & role matrix\n\n";
        $md .= "_Generated by `php spark dgr:docs` from the registry and starter roles in `app/Config/Permissions.php`. Do not edit by hand._\n\n";
        $md .= "Legend: ✔ granted · — not granted · **⚠** dangerous (grant requires password re-entry and shows a warning). Super Admin holds every key implicitly.\n\n";
        $md .= "Roles are owner-editable in **Users & Roles**; this file shows the starter roles a fresh install creates (later edits live in the database).\n\n";
        $md .= "| Code | Role | Description |\n|---|---|---|\n";
        foreach ($roles as $r) {
            $md .= '| `' . $r['code'] . '` | ' . $r['name'] . ($r['is_super'] ? ' (super)' : '') . ' | ' . $r['description'] . " |\n";
        }
        $abbr = array_map(static fn ($r) => $r['code'], $roles);
        foreach ($cfg->modules as $module => $def) {
            $md .= "\n## " . $def['label'] . " (`{$module}.*`)\n\n";
            $md .= '| Permission | Description | ' . implode(' | ', $abbr) . " |\n";
            $md .= '|---|---|' . str_repeat('---|', count($abbr)) . "\n";
            foreach ($def['perms'] as $key => $meta) {
                $danger = ! empty($meta[1]['danger']) ? ' **⚠**' : '';
                $cells  = [];
                foreach ($roles as $r) {
                    $cells[] = ((int) $r['is_super'] === 1 || isset($grant[$key][$r['code']])) ? '✔' : '—';
                }
                $md .= "| `{$key}`{$danger} | " . $meta[0] . ' | ' . implode(' | ', $cells) . " |\n";
            }
        }
        $md .= "\n## AI service-account capabilities (not user permissions — all OFF by default)\n\n| Capability | Purpose | Allowlisted fields |\n|---|---|---|\n";
        foreach ($cfg->aiCapabilities as $code => $cap) {
            $md .= "| `{$code}` | {$cap['label']} | " . implode(', ', array_map(static fn ($f) => '`' . $f . '`', $cap['fields'])) . " |\n";
        }
        $md .= "\n## Separation-of-duties warnings\n\n";
        foreach ($cfg->sodWarnings as [$a, $b, $why]) {
            $md .= "- `{$a}` + `{$b}` — {$why}\n";
        }

        return $md;
    }

    private function schema(): string
    {
        $db     = db_connect();
        $schema = $db->getDatabase();
        $tables = $db->query('SELECT TABLE_NAME, TABLE_COMMENT FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME', [$schema])->getResultArray();
        $fks    = $db->query(
            'SELECT TABLE_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME, CONSTRAINT_NAME FROM information_schema.KEY_COLUMN_USAGE
             WHERE TABLE_SCHEMA = ? AND REFERENCED_TABLE_NAME IS NOT NULL ORDER BY TABLE_NAME, COLUMN_NAME',
            [$schema]
        )->getResultArray();

        $md  = "# Database schema & ERD\n\n_Generated by `php spark dgr:docs` from the migrated MySQL database (`{$schema}`). Do not edit by hand._\n\n";
        $md .= '- Tables: **' . count($tables) . '** · Foreign keys: **' . count($fks) . "**\n";
        $md .= "- Engine InnoDB, charset utf8mb4; money is `DECIMAL(15,2)`, rates `DECIMAL(6,3)`, quantities `DECIMAL(14,3)` — no floating point.\n";
        $md .= "- Shield tables (`users`, `auth_*`) and the Settings library table (`settings`) are created by their own migrations.\n\n";

        $groups = [
            'Billing & finance' => ['billing_', 'payment_', 'money_', 'journal_', 'ledger_', 'bank_', 'reconciliation_', 'expense', 'itc_', 'credit_debit', 'signature_usage', 'recurring_', 'document_sequences', 'tax_', 'services', 'contacts', 'contact_', 'states'],
            'CRM & sync'        => ['leads', 'lead_', 'call_logs', 'followups', 'visits', 'meetings', 'tasks', 'task_', 'crm_', 'lost_reasons', 'google_'],
            'HR, payroll & AI'  => ['employee', 'candidate', 'job_', 'interview', 'recruitment_', 'attendance', 'leave_', 'holidays', 'weekly_', 'salary_', 'statutory_', 'incentive_', 'payroll_', 'payslips', 'departments', 'designations', 'ai_'],
        ];
        foreach ($groups as $title => $prefixes) {
            $md .= "## ERD — {$title}\n\n```mermaid\nerDiagram\n";
            $seen = [];
            foreach ($fks as $fk) {
                $match = static fn (string $t) => array_filter($prefixes, static fn ($p) => str_starts_with($t, $p)) !== [];
                if (! $match($fk['TABLE_NAME'])) {
                    continue;
                }
                $k = $fk['REFERENCED_TABLE_NAME'] . '>' . $fk['TABLE_NAME'] . ':' . $fk['COLUMN_NAME'];
                if (isset($seen[$k])) {
                    continue;
                }
                $seen[$k] = true;
                $md .= '    ' . $fk['REFERENCED_TABLE_NAME'] . ' ||--o{ ' . $fk['TABLE_NAME'] . ' : "' . $fk['COLUMN_NAME'] . "\"\n";
            }
            $md .= "```\n\n";
        }

        $md .= "## Tables\n";
        foreach ($tables as $t) {
            $name = $t['TABLE_NAME'];
            $cols = $db->query(
                'SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, COLUMN_KEY, COLUMN_COMMENT FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION',
                [$schema, $name]
            )->getResultArray();
            $md .= "\n### `{$name}`" . ($t['TABLE_COMMENT'] ? ' — ' . $t['TABLE_COMMENT'] : '') . "\n\n| Column | Type | Null | Default | Key | Notes |\n|---|---|---|---|---|---|\n";
            foreach ($cols as $c) {
                $md .= '| `' . $c['COLUMN_NAME'] . '` | ' . str_replace('|', '\\|', $c['COLUMN_TYPE']) . ' | ' . $c['IS_NULLABLE'] . ' | '
                    . ($c['COLUMN_DEFAULT'] === null ? '' : '`' . str_replace('|', '\\|', (string) $c['COLUMN_DEFAULT']) . '`') . ' | ' . $c['COLUMN_KEY'] . ' | ' . str_replace('|', '\\|', (string) $c['COLUMN_COMMENT']) . " |\n";
            }
            $tfks = array_filter($fks, static fn ($f) => $f['TABLE_NAME'] === $name);
            if ($tfks !== []) {
                $md .= "\nForeign keys: " . implode(', ', array_map(static fn ($f) => '`' . $f['COLUMN_NAME'] . '` → `' . $f['REFERENCED_TABLE_NAME'] . '.' . $f['REFERENCED_COLUMN_NAME'] . '`', $tfks)) . "\n";
            }
            $checks = $db->query(
                'SELECT cc.CONSTRAINT_NAME, cc.CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS cc
                 JOIN information_schema.TABLE_CONSTRAINTS tc ON tc.CONSTRAINT_SCHEMA = cc.CONSTRAINT_SCHEMA AND tc.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
                 WHERE tc.TABLE_SCHEMA = ? AND tc.TABLE_NAME = ?',
                [$schema, $name]
            )->getResultArray();
            if ($checks !== []) {
                $md .= "\nCheck constraints: " . implode('; ', array_map(static fn ($c) => '`' . $c['CONSTRAINT_NAME'] . '`', $checks)) . "\n";
            }
        }

        return $md;
    }
}
