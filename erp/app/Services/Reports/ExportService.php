<?php

namespace App\Services\Reports;

use App\Libraries\SheetIO;
use CodeIgniter\Database\BaseConnection;
use CodeIgniter\HTTP\ResponseInterface;

/**
 * Generates XLSX/CSV exports, stores a private copy, records download
 * history (report_exports) and audits who exported what. Callers must have
 * already authorized the export permission and applied record scopes.
 */
class ExportService
{
    public function __construct(private readonly BaseConnection $db)
    {
    }

    /**
     * @param list<array<string, mixed>> $sheets SheetIO sheet definitions
     * @param array<string, mixed>       $filters
     */
    public function download(string $reportCode, string $format, string $fileBase, array $sheets, array $filters = [], array $meta = []): ResponseInterface
    {
        $format = $format === 'csv' ? 'csv' : 'xlsx';
        $user   = current_user_name();
        $meta   = ['Report' => $meta['Report'] ?? $reportCode] + $meta + [
            'Generated'    => date('d-m-Y h:i A') . ' IST',
            'Generated by' => $user,
            'Filters'      => $this->describe($filters),
            'Note'         => 'Internal document — contains business data. Do not share outside authorised staff.',
        ];
        if ($format === 'csv') {
            $first = $sheets[0];
            $bytes = SheetIO::csv($first['columns'], $first['rows']);
            $mime  = 'text/csv';
        } else {
            $bytes = SheetIO::xlsx($sheets, $meta);
            $mime  = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
        }
        $name   = preg_replace('/[^A-Za-z0-9_\-]+/', '_', $fileBase) . '_' . date('Ymd_His') . '.' . $format;
        $rowCnt = array_sum(array_map(static fn ($s) => count($s['rows']), $sheets));
        $fileId = service('files')->storeContents($bytes, $name, $mime, 'report_export');
        $this->db->table('report_exports')->insert([
            'user_id'        => (int) service('authz')->currentUserId(),
            'report_code'    => $reportCode,
            'format'         => $format,
            'filters'        => json_encode($filters),
            'stored_file_id' => $fileId,
            'row_count'      => $rowCnt,
            'status'         => 'generated',
            'downloaded_at'  => date('Y-m-d H:i:s'),
        ]);
        service('audit')->log('export.generated', 'report_export', (int) $this->db->insertID(), null, null, "Exported {$reportCode} ({$format}, {$rowCnt} rows)", ['filters' => $filters]);

        return service('response')
            ->setHeader('Content-Type', $mime)
            ->setHeader('Content-Disposition', 'attachment; filename="' . $name . '"')
            ->setHeader('Cache-Control', 'private, no-store')
            ->setBody($bytes);
    }

    /** @param array<string, mixed> $filters */
    private function describe(array $filters): string
    {
        $parts = [];
        foreach ($filters as $k => $v) {
            if ($v !== null && $v !== '' && $v !== []) {
                $parts[] = $k . '=' . (is_array($v) ? implode(',', $v) : $v);
            }
        }

        return $parts === [] ? 'none' : implode('; ', $parts);
    }
}
